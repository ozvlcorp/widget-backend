from pydantic_settings import BaseSettings


class Settings(BaseSettings):
    database_url: str = "postgresql+asyncpg://postgres:postgres@db:5432/widgets"
    cors_origins: list[str] = ["*"]

    # Защита /admin/*. Пусто = админские ручки ОТКЛЮЧЕНЫ (503), а не открыты.
    # Раньше пустое значение молча снимало проверку (`if settings.admin_secret
    # and ...`), и любой мог перезаписать app_secret любого виджета.
    admin_secret: str = ""

    # Сколько живёт contextKey. МойСклад выдаёт его на одно открытие виджета;
    # без срока запись оставалась валидной вечно, и ключ месячной давности
    # по-прежнему менялся на токен.
    context_key_ttl_seconds: int = 300

    # АВАРИЙНЫЙ переключатель: выдавать токен по одному accountId или имени
    # аккаунта, без проверки contextKey. Это дыра — кто знает имя аккаунта, тот
    # получает полный доступ к данным МойСклада. Нужен только чтобы пережить
    # окно, пока приложение не зарегистрировано в кабинете вендора.
    allow_insecure_account_fallback: bool = False

    # ─── Синхронизация в собственный Postgres ────────────────────────────────
    # Приложение читает данные из своей базы, а не из МойСклад на каждый клик.
    # Наполняет её фоновый воркер (app/sync.py).

    # Включён ли планировщик в этом процессе. На нескольких репликах оставьте
    # True только у одной — иначе они будут спорить за одни и те же аккаунты
    # (блокировка в ms_sync_runs это переживёт, но смысла в гонке нет).
    sync_enabled: bool = True

    # Расписание в формате cron (мин час день месяц день_недели), UTC.
    # По умолчанию — ежедневно в 02:30 UTC. Вынесено в переменную намеренно:
    # при ночном синке данные за сегодня появляются только после прогона, и
    # частоту почти наверняка захочется поменять без правки кода.
    sync_cron: str = "30 2 * * *"

    # Потолок времени на один прогон одного аккаунта. Первичная заливка всей
    # истории в него не уложится — она и не должна: воркер сохранит курсоры и
    # продолжит следующей ночью.
    sync_max_seconds: int = 3 * 60 * 60

    # Ширина окна при заливке истории, в днях.
    sync_window_days: int = 30

    # Насколько глубоко в прошлое пускать заливку. 0 = до самого раннего
    # документа аккаунта (его находим запросом order=moment,asc&limit=1).
    sync_backfill_max_days: int = 0

    # Сколько прогон считается живым без обновления heartbeat, прежде чем его
    # признают мёртвым и дадут начать новый. Спасает от вечной блокировки после
    # падения контейнера посреди синка.
    sync_stale_run_minutes: int = 90

    @property
    def async_database_url(self) -> str:
        # Dokploy gives postgresql://, we need postgresql+asyncpg://
        return self.database_url.replace(
            "postgresql://", "postgresql+asyncpg://", 1
        )

    class Config:
        env_file = ".env"


settings = Settings()
